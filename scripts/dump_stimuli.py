"""Write every distinct prompt the models receive, verbatim, to one Markdown file for external review.

Usage
  python run_experiment.py --module all --pilot --mock            # zero API calls, builds every prompt
  python scripts/dump_stimuli.py [RUN_ID] [--db data/arena_mock.sqlite] [--out docs/stimuli_verbatim.md]

The prompts are read back from the `calls` table (first attempt of each step), so the file shows exactly what was
sent, not a paraphrase of the code. One example is kept per (module, role, phase, condition); within a trial the
first round (A), the first trap turn (C) or the first step (B) is used. A reviewer can read the whole set in about
15 minutes before the materials are frozen for pre-registration.
"""
from __future__ import annotations

import argparse
import difflib
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from arena.config import load_config, resolve  # noqa: E402

SPEC_KEYS = {"A": ("pressure", "identity", "threat", "item_bank"),
             "B": ("framing", "chain", "strategist_mode"),
             "C": ("condition", "dissident_tone", "banish_criterion")}


def _phase(module: str, step_key: str) -> str | None:
    """Which step of a trial this call is, or None to skip it (later rounds / turns repeat the same prompt)."""
    parts = step_key.split(":")
    if module == "A":
        return parts[-1] if parts[0] == "r01" else None
    if module == "B":
        return parts[0] if parts[0] in ("t1", "t2", "t4") or step_key == "t3:1" else None
    if module == "C":
        # discussion: first trap turn only; ballot: also the nomination turn (t05) and the motion vote (t06)
        if parts[-1] == "talk":
            return "talk" if parts[0] == "t02" else None
        return parts[-1] if parts[0] in ("t02", "t05", "t06") else None
    return None


def collect(con: sqlite3.Connection, run_id: str) -> list[dict]:
    specs = {r[0]: (r[1], json.loads(r[2])) for r in
             con.execute("SELECT trial_id, module, spec_json FROM trials WHERE run_id=?", (run_id,))}
    seen, out = set(), []
    rows = con.execute("SELECT trial_id, step_key, role, model_id, messages_json FROM calls "
                       "WHERE run_id=? AND attempt=0 ORDER BY id", (run_id,)).fetchall()
    for trial_id, step_key, role, model_id, messages_json in rows:
        if trial_id in specs:
            module, spec = specs[trial_id]
            phase = _phase(module, step_key)
            if phase is None:
                continue
            if module == "C" and step_key.startswith(("t05", "t06")):
                phase += (" (turn 5: private nomination)" if step_key.startswith("t05")
                          else " (turn 6: vote on a motion, when one is pending)")
            cond = tuple((k, spec.get(k)) for k in SPEC_KEYS[module] if spec.get(k) is not None)
        elif trial_id.startswith("gate-"):  # baseline gate calls: one per gated module
            module, phase, cond = "gate", "Module " + trial_id.split("-")[1], ()
        else:
            continue
        key = (module, role, phase, cond)
        if key in seen:
            continue
        seen.add(key)
        out.append({"module": module, "role": role, "phase": phase, "cond": dict(cond), "step_key": step_key,
                    "trial_id": trial_id, "model_id": model_id, "messages": json.loads(messages_json)})
    order = {"gate": 0, "A": 1, "B": 2, "C": 3}
    out.sort(key=lambda r: (order.get(r["module"], 9), r["role"] or "", r["phase"], json.dumps(r["cond"])))
    return out


def _text(messages: list[dict]) -> list[str]:
    out = []
    for m in messages:
        out += [f"[{m['role']}]"] + m["content"].rstrip().splitlines() + [""]
    return out


def render(run_id: str, items: list[dict]) -> str:
    lines = ["# Stimuli, verbatim", "",
             f"Generated by `scripts/dump_stimuli.py` from run `{run_id}`; regenerate it after any prompt change. "
             "Every prompt is read back from the database: it is the exact text sent to a model. In a mock run the "
             "numbers, names and orders are drawn exactly as in a live run; only the replies are simulated, so any "
             "earlier speaker's message quoted inside a prompt is mock text.", "",
             "For each module, role and step, the first condition is shown in full (the **reference**). Every other "
             "condition is shown as the lines of the **system prompt** that differ from the reference (`-` reference "
             "line, `+` this condition): that is where the identity framing, the threat rule, the dissident's "
             "instructions and the governance rule live. The user prompts of Modules A and C change every round or "
             "turn (problem, telemetry, discussion) and are only shown in full in the reference. In Module B the "
             "order's wording is in the user prompt, so the whole prompt is compared.", ""]
    groups: dict[tuple, list[dict]] = {}
    for it in items:
        groups.setdefault((it["module"], it["role"], it["phase"]), []).append(it)
    current = None
    for (module, role, phase), its in groups.items():
        if module != current:
            current = module
            lines += ["", f"## {'Baseline gates (solo pre-checks)' if module == 'gate' else 'Module ' + module}", ""]
        ref = its[0]
        cond = ", ".join(f"{k}={v}" for k, v in ref["cond"].items()) or "-"
        lines += [f"### {role} · {phase}", "", f"Reference: {cond} (`{ref['trial_id']}`, step `{ref['step_key']}`, "
                  f"model `{ref['model_id']}`)", "", "````text", *_text(ref["messages"]), "````", ""]
        for it in its[1:]:
            keep = (lambda ms: ms) if module == "B" else (lambda ms: [m for m in ms if m["role"] == "system"])
            diff = [d for d in difflib.unified_diff(_text(keep(ref["messages"])), _text(keep(it["messages"])),
                                                    lineterm="", n=0)
                    if not d.startswith(("---", "+++", "@@"))]
            cond = ", ".join(f"{k}={v}" for k, v in it["cond"].items()) or "-"
            lines += [f"**{cond}**: " + ("same text as the reference" if not diff else f"{len(diff)} changed lines"), ""]
            if diff:
                lines += ["````diff", *diff, "````", ""]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("run_id", nargs="?", help="run to read (default: the latest mock run)")
    ap.add_argument("--db", default=None, help="SQLite database (default: paths.mock_db in config.yaml)")
    ap.add_argument("--out", default=str(ROOT / "docs" / "stimuli_verbatim.md"))
    args = ap.parse_args(argv)
    cfg = load_config()
    con = sqlite3.connect(args.db or resolve(cfg["paths"]["mock_db"]))
    run_id = args.run_id or con.execute("SELECT run_id FROM runs ORDER BY created_at DESC LIMIT 1").fetchone()[0]
    items = collect(con, run_id)
    Path(args.out).write_text(render(run_id, items), encoding="utf-8")
    print(f"{len(items)} distinct prompts from {run_id} -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
